#!/usr/bin/env python3
"""Writes lib/data/bc_flow_ranges.dart from flow_ranges.json.

The app bundles these low / medium / high flows so they show without a
database write. Edit flow_ranges.json, then run:

    python3 scripts/bcwhitewater/gen_flow_ranges.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def dart(value):
    if isinstance(value, str):
        return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(float(value)) if isinstance(value, float) else str(value)
    raise TypeError(value)


def main():
    with open(os.path.join(HERE, 'flow_ranges.json'), encoding='utf-8') as f:
        ranges = json.load(f)
    with open(os.path.join(HERE, 'bc_whitewater_all_data_with_stations.json'), encoding='utf-8') as f:
        names = {r['slug']: r['title'] for r in json.load(f)['reaches']}

    lines = [
        '// GENERATED by scripts/bcwhitewater/gen_flow_ranges.py from',
        '// scripts/bcwhitewater/flow_ranges.json. Do not edit by hand.',
        '',
        '/// Low / medium / high flows per run from BC Whitewater, keyed by run',
        '/// id. See [FlowRanges].',
        'const bcFlowRanges = <String, Map<String, Object>>{',
    ]
    for slug in sorted(k for k in ranges if not k.startswith('_')):
        entry = {'name': names[slug], **ranges[slug]}
        body = ', '.join(f"'{k}': {dart(v)}" for k, v in entry.items())
        lines.append(f"  '{slug}': {{{body}}},")
    lines.append('};')
    out = os.path.join(ROOT, 'lib', 'data', 'bc_flow_ranges.dart')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'Wrote {len(ranges) - 1} runs to {os.path.relpath(out, ROOT)}')


if __name__ == '__main__':
    main()
